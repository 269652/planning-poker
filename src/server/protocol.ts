import { z } from 'zod';
import type { RoomView } from '@/core/view';

/**
 * Wire protocol (JSON text frames over one websocket per client).
 *
 * client -> server
 *   join    { roomId, roomName?, clientKey, name, role? }   must be the first message
 *   action  { action }                                       planning actions (see below)
 *   jira    { reqId, op, ... }                               Jira browse/import/write-back (host only, except status)
 *   ping
 *
 * server -> client
 *   state       { version, view }                            full per-client projection after every change
 *   error       { code, message }
 *   jiraResult  { reqId, ok, data?, error? }
 *   pong
 *
 * `clientKey` is a secret generated by the browser and never echoed back; the
 * public participant id is a hash of it, so ids in `view` cannot be used to
 * impersonate anyone.
 */

const card = z.union([z.number(), z.literal('?'), z.literal('coffee')]);

/** Actions a client may send. Import and system actions are deliberately absent. */
export const clientAction = z.discriminatedUnion('type', [
  z.object({ type: z.literal('rename'), name: z.string().max(200) }),
  z.object({ type: z.literal('setRole'), role: z.enum(['voter', 'observer']), target: z.string().max(64).optional() }),
  z.object({ type: z.literal('transferHost'), to: z.string().max(64) }),
  z.object({ type: z.literal('setSettings'), autoReveal: z.boolean().optional(), writeBack: z.enum(['auto', 'manual']).optional() }),
  z.object({
    type: z.literal('addTicket'),
    ticket: z.object({
      title: z.string().max(300),
      key: z.string().max(50).nullish(),
      description: z.string().max(8000).optional(),
    }),
  }),
  z.object({ type: z.literal('removeTicket'), ticketId: z.string().max(20) }),
  z.object({ type: z.literal('selectTicket'), ticketId: z.string().max(20) }),
  z.object({ type: z.literal('vote'), card }),
  z.object({ type: z.literal('retract') }),
  z.object({ type: z.literal('reveal') }),
  z.object({ type: z.literal('revote') }),
  z.object({ type: z.literal('accept'), value: z.number().optional() }),
  z.object({ type: z.literal('skip') }),
  z.object({ type: z.literal('reopen'), ticketId: z.string().max(20) }),
]);

const jiraOp = z.discriminatedUnion('op', [
  z.object({ op: z.literal('status') }),
  z.object({ op: z.literal('boards'), query: z.string().max(100).optional() }),
  z.object({ op: z.literal('sprints'), boardId: z.number().int() }),
  z.object({
    op: z.literal('import'),
    boardId: z.number().int(),
    sprintId: z.number().int().optional(),
    jql: z.string().max(1000).optional(),
  }),
  z.object({ op: z.literal('writeBack'), ticketId: z.string().max(20) }),
]);

export const ROOM_ID = /^[A-Za-z0-9_-]{3,40}$/;

export const clientMessage = z.union([
  z.object({
    type: z.literal('join'),
    roomId: z.string().regex(ROOM_ID),
    roomName: z.string().max(80).optional(),
    clientKey: z.string().min(16).max(128),
    name: z.string().max(200),
    role: z.enum(['voter', 'observer']).optional(),
  }),
  z.object({ type: z.literal('action'), action: clientAction }),
  z.object({ type: z.literal('ping') }),
  z.intersection(z.object({ type: z.literal('jira'), reqId: z.string().max(40) }), jiraOp),
]);

export type ClientMessage = z.infer<typeof clientMessage>;

export type ServerMessage =
  | { type: 'state'; version: number; view: RoomView }
  | { type: 'error'; code: string; message: string }
  | { type: 'jiraResult'; reqId: string; ok: boolean; data?: unknown; error?: string }
  | { type: 'pong' };
